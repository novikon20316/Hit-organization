// src/scripts/generateAssistantManuals.ts
//
// Regenerates src/assistant/manualTexts.ts — the plain text of each role's
// user manual (repo-root manuals/*.docx), which the in-app help assistant
// (services/assistantService.ts) answers from. The text is committed as a TS
// module rather than read from the .docx at runtime so the Docker build
// (server/ only) carries it and every change to what the assistant knows
// shows up in review as a diff.
//
// Re-run whenever a manual in manuals/ changes. Writes only the one file;
// touches no data.
//
// Usage (from server/):
//   npx tsx src/scripts/generateAssistantManuals.ts

import fs from 'fs';
import path from 'path';
// @ts-ignore — word-extractor ships no type definitions.
import WordExtractor from 'word-extractor';

const MANUALS_DIR = path.resolve('..', 'manuals');
const OUT_FILE = path.resolve('src', 'assistant', 'manualTexts.ts');

// Manual file (without .docx) per key. system_admin is deliberately absent:
// the assistant isn't offered to that role.
const SOURCES: Record<string, string> = {
  student: 'מדריך_סטודנט',
  studentProcess: 'חוברת_תפקידים_ותהליך_הסטודנט',
  supervisor: 'מדריך_מנחה',
  coordinator: 'מדריך_רכז_פקולטה',
  administrative_secretary: 'מדריך_רכזת_אדמיניסטרטיבית',
  faculty_admin: 'מדריך_ראש_מנהל_פקולטה',
  program_head: 'מדריך_ראש_תוכנית',
  division_head: 'מדריך_ראש_תחום',
  dean: 'מדריך_דיקן',
  grad_school_head: 'מדריך_ראש_בית_הספר_ללימודי_מוסמכים',
  school_head: 'מדריך_ראש_בית_ספר',
  internal_examiner: 'מדריך_בוחן_פנימי',
};

function clean(body: string): string {
  return body
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.replace(/\t+$/, '').trimEnd())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

async function main() {
  const extractor = new WordExtractor();
  const texts: Record<string, string> = {};
  for (const [key, file] of Object.entries(SOURCES)) {
    const doc = await extractor.extract(path.join(MANUALS_DIR, `${file}.docx`));
    texts[key] = clean(doc.getBody());
    console.log(`${key.padEnd(26)} ${String(texts[key].length).padStart(6)} chars  (${file}.docx)`);
  }

  const lines = [
    '// src/assistant/manualTexts.ts',
    '//',
    '// GENERATED by src/scripts/generateAssistantManuals.ts from manuals/*.docx —',
    '// do not edit by hand; edit the manual and re-run the script.',
    '',
    'export const MANUAL_TEXTS = {',
    ...Object.entries(texts).map(([key, text]) => `  ${key}: ${JSON.stringify(text)},`),
    '} as const;',
    '',
    'export type ManualKey = keyof typeof MANUAL_TEXTS;',
    '',
  ];
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');
  console.log(`Wrote ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
